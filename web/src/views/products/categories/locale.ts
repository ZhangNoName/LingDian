export function useCategoryLocale() {
  const { locale } = useLocale()
  return {
    t: (key: Key) => (locale.value === 'en-US' ? en : zh)[key],
    number: (n: number | undefined) => n === undefined ? '—' : n.toLocaleString(locale.value),
  }
}
export function categoryError(error: unknown): Key {
  const message = error instanceof Error ? error.message.replace(/^catalog\./, '') : ''
  return Object.hasOwn(zh, message) ? (message as Key) : 'saveFailed'
}
