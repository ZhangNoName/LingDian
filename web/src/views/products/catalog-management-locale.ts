export function useCatalogLocale() {
  const { locale } = useLocale()
  return { t: (key: CatalogKey) => (locale.value === 'en-US' ? en : zh)[key] }
}
export function catalogError(error: unknown): CatalogKey {
  const source = error instanceof Error ? error.message.replace(/^catalog\./, '') : ''
  return Object.hasOwn(zh, source) ? (source as CatalogKey) : 'saveFailed'
}
