export function useLifecycleLocale() {
  const { locale } = useLocale()
  return { locale, t: (key: LifecycleKey) => (locale.value === 'en-US' ? en : zh)[key] }
}
export function lifecycleError(error: unknown): LifecycleKey {
  const code = error instanceof Error ? error.message : ''
  const keys: Record<string, LifecycleKey> = {
    'inventory.stale': 'stale',
    'inventory.archiveStock': 'stock',
    'inventory.archiveRecipe': 'recipe',
    'inventory.archivePurchase': 'purchase',
    'inventory.archiveStocktake': 'stocktake',
    'inventory.notFound': 'notFound',
  }
  return keys[code] ?? 'failed'
}
