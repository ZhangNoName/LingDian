export function useTrendLocale() {
  const { locale } = useLocale()
  return {
    t: (key: TrendKey) => (locale.value === 'en-US' ? en : zh)[key],
    axis: (value: number) =>
      new Intl.NumberFormat(locale.value, {
        notation: Math.abs(value) >= 10000 ? 'compact' : 'standard',
        maximumFractionDigits: 1,
      }).format(value),
    number: (value: number | null) =>
      value === null ? '—' : value.toLocaleString(locale.value, { maximumFractionDigits: 3 }),
    day: (value: string) =>
      new Intl.DateTimeFormat(locale.value, { timeZone: 'UTC', month: '2-digit', day: '2-digit' }).format(
        new Date(value + 'T00:00:00Z'),
      ),
  }
}
