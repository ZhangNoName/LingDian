export function useAnalysisLocale() {
  const { locale } = useLocale()
  return {
    t: (key: Key) => (locale.value === 'en-US' ? en : zh)[key],
    number: (value: number) => value.toLocaleString(locale.value, { maximumFractionDigits: 3 }),
    percent: (rate: number | null) =>
      rate === null
        ? '—'
        : rate > 0 && rate < 0.0001
          ? '<' + new Intl.NumberFormat(locale.value, { style: 'percent', maximumFractionDigits: 2 }).format(0.0001)
          : new Intl.NumberFormat(locale.value, { style: 'percent', maximumFractionDigits: 2 }).format(rate),
  }
}
