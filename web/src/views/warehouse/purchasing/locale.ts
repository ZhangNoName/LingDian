export function usePurchasingLocale() {
  const { locale } = useLocale()
  return {
    locale,
    t: (key: Key) => (locale.value === 'en-US' ? en : zh)[key],
    number: (n: number) => n.toLocaleString(locale.value, { maximumFractionDigits: 3 }),
    money: (cents: number) =>
      new Intl.NumberFormat(locale.value, {
        style: 'currency',
        currency: 'CNY',
        currencyDisplay: 'narrowSymbol',
      }).format(cents / 100),
    date: (value: string | null) =>
      value
        ? new Intl.DateTimeFormat(locale.value, { dateStyle: 'short', timeStyle: 'short' }).format(new Date(value))
        : '—',
  }
}
export function errorKey(error: unknown): Key {
  const code = error instanceof Error ? error.message : ''
  const key = code.replace(/^purchasing\./, '') as Key
  return Object.hasOwn(zh, key) ? key : 'saveFailed'
}
