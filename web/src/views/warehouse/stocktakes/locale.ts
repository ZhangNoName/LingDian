export function useStocktakeLocale() {
  const { locale } = useLocale()
  return {
    locale,
    t: (key: Key) => (locale.value === 'en-US' ? en : zh)[key],
    number: (value: number) => value.toLocaleString(locale.value, { maximumFractionDigits: 3 }),
    date: (value: string | null) =>
      value
        ? new Intl.DateTimeFormat(locale.value, { dateStyle: 'short', timeStyle: 'short' }).format(new Date(value))
        : '—',
  }
}
export function errorKey(error: unknown): Key {
  const message = error instanceof Error ? error.message.replace(/^stocktake\./, '') : ''
  return Object.hasOwn(zh, message) ? (message as Key) : 'saveFailed'
}
